class PdmWriterService {
  String buildPdmXml({
    required ReverseSchemaModel schema,
    required String modelName,
    required String sourcePath,
  }) {
    final targetModel = _resolveTargetModel(schema.databaseType);
    final writerContext = _PdmWriterContext(
      modelName: modelName,
      targetModel: targetModel,
    );
    final dbmsShortcutXmlId = writerContext.nextXmlId();
    final rootXmlId = writerContext.nextXmlId();
    final modelXmlId = writerContext.nextXmlId();
    final builder = XmlBuilder();
    builder.processing('xml', 'version="1.0" encoding="UTF-8"');
    builder.processing(
      'PowerDesigner',
      'AppLocale="UTF16" '
          'ID="{${writerContext.modelObjectId}}" '
          'Label="${_escapeProcessingInstructionValue(modelName)}" '
          'LastModificationDate="${writerContext.timestampSeconds}" '
          'Name="${_escapeProcessingInstructionValue(modelName)}" '
          'Objects="${writerContext.estimatedObjectCount(schema)}" '
          'Symbols="0" '
          'Target="${targetModel.displayName}" '
          'Type="{CDE44E21-9669-11D1-9914-006097355D9B}" '
          'signature="PDM_DATA_MODEL_XML" '
          'version="16.7.4.6866"',
    );
    builder.comment(' do not edit this file ');
    builder.element(
      'Model',
      nest: () {
        builder.namespace('attribute', 'a');
        builder.namespace('collection', 'c');
        builder.namespace('object', 'o');
        builder.element(
          'o:RootObject',
          attributes: {'Id': rootXmlId},
          nest: () {
            builder.element(
              'a:SessionID',
              nest: '00000000-0000-0000-0000-000000000000',
            );
            builder.element(
              'c:Children',
              nest: () {
                builder.element(
                  'o:Model',
                  attributes: {'Id': modelXmlId},
                  nest: () {
                    _writeCommonObjectMetadata(
                      builder,
                      objectId: writerContext.modelObjectId,
                      name: modelName,
                      code: modelName,
                      comment: modelName,
                      timestampSeconds: writerContext.timestampSeconds,
                    );
                    builder.element(
                      'a:PackageOptionsText',
                      nest: _defaultPackageOptionsText,
                    );
                    builder.element(
                      'a:RepositoryFilename',
                      nest: sourcePath,
                    );
                    builder.element(
                      'c:DBMS',
                      nest: () {
                        builder.element(
                          'o:Shortcut',
                          attributes: {'Id': dbmsShortcutXmlId},
                          nest: () {
                            _writeCommonObjectMetadata(
                              builder,
                              objectId: writerContext.nextObjectId(),
                              name: targetModel.displayName,
                              code: targetModel.code,
                              comment: '',
                              timestampSeconds:
                                  writerContext.timestampSeconds,
                              includeComment: false,
                            );
                            builder.element('a:TargetStereotype');
                            builder.element(
                              'a:TargetID',
                              nest: targetModel.targetModelId,
                            );
                            builder.element(
                              'a:TargetClassID',
                              nest: targetModel.targetModelClassId,
                            );
                          },
                        );
                      },
                    );
                    builder.element(
                      'c:Tables',
                      nest: () {
                        for (var tableIndex = 0;
                            tableIndex < schema.tables.length;
                            tableIndex++) {
                          final table = schema.tables[tableIndex];
                          final tableId = writerContext.nextXmlId();
                          final extendedCollectionId =
                              writerContext.nextXmlId();
                          final keyId = writerContext.nextXmlId();
                          builder.element(
                            'o:Table',
                            attributes: {'Id': tableId},
                            nest: () {
                              _writeCommonObjectMetadata(
                                builder,
                                objectId: writerContext.nextObjectId(),
                                name: table.name,
                                code: table.code,
                                comment: table.comment,
                                timestampSeconds:
                                    writerContext.timestampSeconds,
                              );
                              builder.element(
                                'a:TotalSavingCurrency',
                                nest: '',
                              );
                              builder.element(
                                'c:ExtendedCollections',
                                nest: () {
                                  builder.element(
                                    'o:ExtendedCollection',
                                    attributes: {'Id': extendedCollectionId},
                                    nest: () {
                                      _writeCommonObjectMetadata(
                                        builder,
                                        objectId: writerContext.nextObjectId(),
                                        name: 'Related Columns',
                                        code: '',
                                        comment: '',
                                        timestampSeconds:
                                            writerContext.timestampSeconds,
                                        includeCode: false,
                                        includeComment: false,
                                      );
                                      builder.element(
                                        'a:ExtendedBaseCollection.CollectionName',
                                        nest: 'Related Columns',
                                      );
                                    },
                                  );
                                },
                              );
                              builder.element(
                                'c:Columns',
                                nest: () {
                                  for (var columnIndex = 0;
                                      columnIndex < table.columns.length;
                                      columnIndex++) {
                                    final column = table.columns[columnIndex];
                                    final columnId = writerContext.nextXmlId();
                                    writerContext.columnXmlIdsByCode[
                                            '${table.rawIdentifier}:${column.ordinalPosition}:${column.code}'] =
                                        columnId;
                                    builder.element(
                                      'o:Column',
                                      attributes: {'Id': columnId},
                                      nest: () {
                                        _writeCommonObjectMetadata(
                                          builder,
                                          objectId:
                                              writerContext.nextObjectId(),
                                          name: column.name,
                                          code: column.code,
                                          comment: column.comment,
                                          timestampSeconds:
                                              writerContext.timestampSeconds,
                                        );
                                        builder.element(
                                          'a:DataType',
                                          nest: _normalizeDataType(column),
                                        );
                                        if (_shouldWriteLength(column)) {
                                          builder.element(
                                            'a:Length',
                                            nest: _normalizedLength(column),
                                          );
                                        }
                                        if (_shouldWritePrecision(column)) {
                                          builder.element(
                                            'a:Precision',
                                            nest: _normalizedPrecision(column),
                                          );
                                        }
                                        builder.element(
                                          'a:Column.Mandatory',
                                          nest: column.nullable ? '0' : '1',
                                        );
                                        if (column.defaultValue.trim().isNotEmpty) {
                                          builder.element(
                                            'a:DefaultValue',
                                            nest: column.defaultValue.trim(),
                                          );
                                        }
                                      },
                                    );
                                  }
                                },
                              );

                              final primaryColumns = table.columns
                                  .where((column) => column.isPrimaryKey)
                                  .toList(growable: false);
                              if (primaryColumns.isNotEmpty) {
                                builder.element(
                                  'c:Keys',
                                  nest: () {
                                    builder.element(
                                      'o:Key',
                                      attributes: {'Id': keyId},
                                      nest: () {
                                        _writeCommonObjectMetadata(
                                          builder,
                                          objectId:
                                              writerContext.nextObjectId(),
                                          name: 'Key_1',
                                          code: 'Key_1',
                                          comment: '',
                                          timestampSeconds:
                                              writerContext.timestampSeconds,
                                          includeComment: false,
                                        );
                                        builder.element(
                                          'c:Key.Columns',
                                          nest: () {
                                            for (final columnEntry
                                                in primaryColumns) {
                                              final columnId = writerContext
                                                  .columnXmlIdsByCode[
                                                      '${table.rawIdentifier}:${columnEntry.ordinalPosition}:${columnEntry.code}'];
                                              if (columnId == null) {
                                                continue;
                                              }
                                              builder.element(
                                                'o:Column',
                                                attributes: {'Ref': columnId},
                                              );
                                            }
                                          },
                                        );
                                      },
                                    );
                                  },
                                );
                                builder.element(
                                  'c:PrimaryKey',
                                  nest: () {
                                    builder.element(
                                      'o:Key',
                                      attributes: {'Ref': keyId},
                                    );
                                  },
                                );
                              }
                            },
                          );
                        }
                      },
                    );
                    builder.element(
                      'c:DefaultGroups',
                      nest: () {
                        builder.element(
                          'o:Group',
                          attributes: {'Id': writerContext.nextXmlId()},
                          nest: () {
                            _writeCommonObjectMetadata(
                              builder,
                              objectId: writerContext.nextObjectId(),
                              name: 'PUBLIC',
                              code: 'PUBLIC',
                              comment: '',
                              timestampSeconds:
                                  writerContext.timestampSeconds,
                              includeComment: false,
                            );
                          },
                        );
                      },
                    );
                    builder.element(
                      'c:TargetModels',
                      nest: () {
                        builder.element(
                          'o:TargetModel',
                          attributes: {'Id': writerContext.nextXmlId()},
                          nest: () {
                            _writeCommonObjectMetadata(
                              builder,
                              objectId: writerContext.nextObjectId(),
                              name: targetModel.displayName,
                              code: targetModel.code,
                              comment: '',
                              timestampSeconds:
                                  writerContext.timestampSeconds,
                              includeComment: false,
                            );
                            builder.element(
                              'a:TargetModelURL',
                              nest: targetModel.url,
                            );
                            builder.element(
                              'a:TargetModelID',
                              nest: targetModel.targetModelId,
                            );
                            builder.element(
                              'a:TargetModelClassID',
                              nest: targetModel.targetModelClassId,
                            );
                            builder.element(
                              'a:TargetModelLastModificationDate',
                              nest: targetModel.lastModificationDate,
                            );
                            builder.element(
                              'c:SessionShortcuts',
                              nest: () {
                                builder.element(
                                  'o:Shortcut',
                                  attributes: {'Ref': dbmsShortcutXmlId},
                                );
                              },
                            );
                          },
                        );
                      },
                    );
                  },
                );
              },
            );
          },
        );
      },
    );
    return builder.buildDocument().toXmlString(pretty: true);
  }

  ParsedPdmFile toParsedPdmFile({
    required ReverseSchemaModel schema,
    required String sourcePath,
    required String sourceName,
  }) {
    return ParsedPdmFile(
      modelName: schema.dataSourceName,
      sourcePath: sourcePath,
      sourceName: sourceName,
      tables: schema.tables
          .map(
            (table) => ParsedPdmTable(
              id: table.rawIdentifier,
              name: table.name,
              code: table.code,
              comment: table.comment,
              columns: table.columns
                  .map(
                    (column) => ParsedPdmColumn(
                      id: '${table.rawIdentifier}:${column.ordinalPosition}:${column.code}',
                      name: column.name,
                      code: column.code,
                      comment: column.comment,
                      dataType: _normalizeDataType(column),
                      length: column.length,
                      precision: column.precision,
                      nullable: column.nullable,
                      defaultValue: column.defaultValue,
                      isPrimaryKey: column.isPrimaryKey,
                    ),
                  )
                  .toList(growable: false),
            ),
          )
          .toList(growable: false),
    );
  }

  String _normalizeDataType(ReverseColumnModel column) {
    final baseType = column.dataType.trim();
    final length = column.length.trim();
    final precision = column.precision.trim();
    if (baseType.isEmpty || _hasInlineTypeArguments(baseType) || length.isEmpty) {
      return baseType;
    }
    if (precision.isNotEmpty && precision != '0') {
      return '$baseType($length,$precision)';
    }
    return '$baseType($length)';
  }
}

void _writeCommonObjectMetadata(
  XmlBuilder builder, {
  required String objectId,
  required String name,
  required String code,
  required String comment,
  required String timestampSeconds,
  bool includeCode = true,
  bool includeComment = true,
}) {
  builder.element('a:ObjectID', nest: objectId);
  builder.element('a:Name', nest: name);
  if (includeCode) {
    builder.element('a:Code', nest: code);
  }
  builder.element('a:CreationDate', nest: timestampSeconds);
  builder.element('a:Creator', nest: 'PdmViewer');
  builder.element('a:ModificationDate', nest: timestampSeconds);
  builder.element('a:Modifier', nest: 'PdmViewer');
  if (includeComment && comment.trim().isNotEmpty) {
    builder.element('a:Comment', nest: comment);
  }
  builder.element('a:GlobalObjectID');
}

String _escapeProcessingInstructionValue(String value) {
  return value
      .replaceAll('&', '&amp;')
      .replaceAll('"', '&quot;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;');
}

bool _hasInlineTypeArguments(String value) {
  return value.contains('(') && value.contains(')');
}

bool _isTimestampLikeType(String value) {
  final normalized = value.trim().toUpperCase();
  return normalized.startsWith('TIMESTAMP') ||
      normalized.startsWith('DATE') ||
      normalized.startsWith('DATETIME') ||
      normalized.startsWith('TIME');
}

bool _shouldWriteLength(ReverseColumnModel column) {
  return _normalizedLength(column).isNotEmpty;
}

String _normalizedLength(ReverseColumnModel column) {
  final length = column.length.trim();
  final precision = column.precision.trim();
  if (length.isEmpty) {
    return '';
  }
  if (_isTimestampLikeType(column.dataType)) {
    return precision == '0' || precision.isEmpty ? length : precision;
  }
  return length;
}

bool _shouldWritePrecision(ReverseColumnModel column) {
  final precision = _normalizedPrecision(column);
  return precision.isNotEmpty && precision != '0';
}

String _normalizedPrecision(ReverseColumnModel column) {
  final length = column.length.trim();
  final precision = column.precision.trim();
  if (precision.isEmpty || precision == '0') {
    return '';
  }
  if (_isTimestampLikeType(column.dataType)) {
    return length;
  }
  return precision;
}


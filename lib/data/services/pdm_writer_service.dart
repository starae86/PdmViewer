_PdmTargetModelDescriptor _resolveTargetModel(JdbcDatabaseType databaseType) {
  return const _PdmTargetModelDescriptor(
    displayName: 'ORACLE Version 11g',
    code: 'ORA11GR1',
    url: 'file:///%[XDB]%/ora11g.xdb',
    targetModelId: 'BAE632F3-AC04-4059-9893-259ABA89351C',
    targetModelClassId: '4BA9F647-DAB1-11D1-9944-006097355D9B',
    lastModificationDate: '1350030902',
  );
}

class _PdmWriterContext {
  _PdmWriterContext({
    required this.modelName,
    required this.targetModel,
  })  : timestampSeconds =
            (DateTime.now().millisecondsSinceEpoch ~/ 1000).toString(),
        modelObjectId = const Uuid().v4().toUpperCase();

  final String modelName;
  final _PdmTargetModelDescriptor targetModel;
  final String timestampSeconds;
  final String modelObjectId;
  final Map<String, String> columnXmlIdsByCode = <String, String>{};

  int _xmlIdSeed = 1;

  String nextXmlId() => 'o${_xmlIdSeed++}';

  String nextObjectId() => const Uuid().v4().toUpperCase();

  int estimatedObjectCount(ReverseSchemaModel schema) {
    final tableCount = schema.tables.length;
    final columnCount = schema.tables.fold<int>(
      0,
      (sum, table) => sum + table.columns.length,
    );
    final keyCount = schema.tables
        .where((table) => table.columns.any((column) => column.isPrimaryKey))
        .length;
    const fixedObjects = 4;
    return fixedObjects + tableCount + columnCount + keyCount + tableCount;
  }
}

class _PdmTargetModelDescriptor {
  const _PdmTargetModelDescriptor({
    required this.displayName,
    required this.code,
    required this.url,
    required this.targetModelId,
    required this.targetModelClassId,
    required this.lastModificationDate,
  });

  final String displayName;
  final String code;
  final String url;
  final String targetModelId;
  final String targetModelClassId;
  final String lastModificationDate;
}
